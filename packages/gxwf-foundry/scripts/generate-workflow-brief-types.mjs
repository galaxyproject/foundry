import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";

const source = new URL("../src/schemas/workflow-brief/workflow-brief.schema.json", import.meta.url);
const output = new URL(
  "../src/schemas/workflow-brief/workflow-brief.types.generated.ts",
  import.meta.url,
);
const schema = JSON.parse(readFileSync(source, "utf8"));

function typeOf(node) {
  if (node.$ref) {
    const name = node.$ref.replace("#/$defs/", "");
    if (!schema.$defs[name]) throw new Error(`Unknown definition: ${node.$ref}`);
    return `WorkflowBrief${name}`;
  }
  if ("const" in node) return JSON.stringify(node.const);
  if (node.enum) return node.enum.map((value) => JSON.stringify(value)).join(" | ");
  if (Array.isArray(node.type))
    return node.type.map((type) => typeOf({ ...node, type })).join(" | ");
  if (node.type === "array") return `Array<${typeOf(node.items)}>`;
  if (node.type === "object") {
    const fields = Object.entries(node.properties).map(
      ([key, value]) => `${key}${node.required?.includes(key) ? "" : "?"}: ${typeOf(value)};`,
    );
    return `{\n${fields.join("\n")}\n}`;
  }
  if (node.type === "integer" || node.type === "number") return "number";
  if (["string", "boolean", "null"].includes(node.type)) return node.type;
  throw new Error(`Unsupported Workflow Brief type: ${JSON.stringify(node)}`);
}

const banner = "// Generated by scripts/generate-workflow-brief-types.mjs. Do not edit.\n";
const definitions = Object.entries(schema.$defs).map(
  ([name, value]) => `export type WorkflowBrief${name} = ${typeOf(value)};`,
);
const text = await format(
  `${banner}export type WorkflowBrief = ${typeOf(schema)};\n\n${definitions.join("\n\n")}\n`,
  {
    ...(await resolveConfig(fileURLToPath(output))),
    parser: "typescript",
  },
);
if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== text)
    throw new Error("Workflow Brief declarations are stale; run pnpm sync.");
} else {
  writeFileSync(output, text);
  console.log(`generated ${fileURLToPath(output)}`);
}
